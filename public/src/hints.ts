/** Прямые одной фразой: имена перечисляются, слово согласуется с их числом. */
function lineList(names: string[]): string {
  return names.length === 1 ? `прямой ${names[0]}` : `прямых ${names.join(', ')}`;
}

/** Подсказка у курсора: что сделает клик и с какими прямыми. */
export function trimHint(
  point: string,
  names: string[],
  side: string,
  back: boolean
): string {
  const what = back ? 'вернуть хвост' : 'отсечь';
  return `${point} · ${what}${side ? ` ${side}` : ''} у ${lineList(names)}`;
}

/** Сообщение после клика: хвост снят или возвращен, и с какими прямыми. */
export function trimDone(names: string[], back: boolean): string {
  if (back) {
    return names.length === 1
      ? `Хвост у прямой ${names[0]} возвращён`
      : `Хвосты у прямых ${names.join(', ')} возвращены`;
  }
  return names.length === 1
    ? `Прямая ${names[0]} отсечена`
    : `Прямые ${names.join(', ')} отсечены`;
}

